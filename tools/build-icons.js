// Builds icons.js: the Lucide icon set inlined as an SVG sprite (no runtime dependency).
// Run from the project folder: node tools/build-icons.js
// Icons are fetched from the public Iconify API (prefix "lucide"). Add or change a mapping below and run it again.
const fs = require('fs');
const path = require('path');

const MAP = {
  snowflake:'snowflake', 'file-in':'file-input', 'file-out':'file-output', 'list-x':'list-x', undo:'rotate-ccw', 'id-card':'id-card', mars:'mars', venus:'venus', 'user-x':'user-round-x',
  // Sidebar, exactly as on the live app (lucide-react)
  grid:'layout-grid', headset:'headset', users:'users', fingerprint:'fingerprint-pattern', card:'credit-card',
  megaphone:'megaphone', 'check-sq':'clipboard-check', file:'file-text', clipboard:'clipboard-minus', export:'file-down',
  staff:'users', settings:'settings', sliders:'settings-2', sidebar:'panel-left-close', back:'chevron-left',
  updown:'chevrons-up-down', 'chev-u':'chevron-up', 'chev-d':'chevron-down', 'chev-r':'chevron-right', 'chev-l':'chevron-left',
  more:'ellipsis-vertical', phone:'phone', flag:'flag', clock:'clock', cal:'calendar', eye:'eye', 'refresh':'refresh-cw',
  'check-c':'circle-check', 'user-check':'user-check', 'chart-col':'chart-column', activity:'activity', pin:'map-pin',
  // Material icons on live, mapped to the nearest Lucide icon
  crumb:'text-align-start', search:'search', rocket:'rocket', plus:'plus', mail:'mail', msg:'message-circle',
  copy:'copy', pencil:'pencil', info:'info', 'alert-c':'circle-alert', star:'star', 'receipt-text':'receipt-text',
  receipt:'receipt', 'cal-check':'calendar-check', 'msg-sq':'message-square', wallet:'wallet', 'cloud-up':'cloud-upload',
  // Used by prototype-only pieces
  upload:'upload', download:'download', filter:'sliders-horizontal', columns:'columns-3', x:'x', check:'check', user:'user',
  help:'circle-question-mark', empty:'inbox', note:'sticky-note', swap:'arrow-left-right', history:'clock-arrow-up',
  logout:'log-out', sun:'sun', moon:'moon', monitor:'monitor', grip:'grip-vertical', list:'list', 'cal-x':'calendar-x',
  repeat:'repeat', 'arrow-down':'arrow-down', trend:'trending-up', 'cal-plus':'calendar-plus', 'user-plus':'user-plus', 'cal-clock':'calendar-clock', 'user-pen':'user-round-pen', hourglass:'hourglass', target:'target',
};

(async () => {
  // One request for the whole set: the Iconify API rate-limits many small calls.
  const ids = Object.values(MAP).join(',');
  const res = await fetch('https://api.iconify.design/lucide.json?icons=' + ids);
  const data = await res.json();
  const symbols = [];
  const missing = [];
  for (const [key, id] of Object.entries(MAP)) {
    const icon = data.icons[id];
    if (!icon) { missing.push(key + ' -> lucide:' + id); continue; }
    symbols.push('<symbol id="i-' + key + '" viewBox="0 0 24 24"><g fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round" stroke-width="2">' + icon.body + '</g></symbol>');
  }
  const sprite = '<svg width="0" height="0" style="position:absolute" aria-hidden="true">' + symbols.join('') + '</svg>';
  const out = `/* Generated by tools/build-icons.js. Lucide icons, inlined as a sprite. */\ndocument.body.insertAdjacentHTML('afterbegin', ${JSON.stringify(sprite)});\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'icons.js'), out);
  console.log('wrote ' + symbols.length + ' icons');
  if (missing.length) console.log('MISSING:', missing.join(', '));
})();
