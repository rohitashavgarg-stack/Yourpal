#!/usr/bin/env node
/*
 * Keeps the design skill (.claude/skills/yourpal-mobile-ui) in step with the code, with no AI and no network. Run by hand, by `npm run skill:learn`,
 * by `scripts/publish.js` and (if you install the optional Stop hook, see docs/AUTOMATION.md) after every Claude turn.
 *
 *   1. catalog.md        regenerated from the code: library components (docs/design-system-components.md), Button kinds and sizes, tokens, the rules in CLAUDE.md
 *   2. CHANGELOG.md      one entry per new commit that touched the UI, grouped by area
 *   3. pending-review.md what changed that a person or the learner agent should turn into a rule: new or removed components, new Button kinds,
 *                        changed rules, new designer feedback in memory. Cleared by the yourpal-design-learner agent.
 *
 *   node scripts/skill/learn.js [--quiet]
 */
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const root = path.resolve(__dirname, '../..');
const skill = path.join(root, '.claude/skills/yourpal-mobile-ui');
const stateFile = path.join(skill, '.learned-state.json');
const quiet = process.argv.includes('--quiet');
const log = (...a) => { if (!quiet) console.log(...a); };
const sh = (cmd) => { try { return execSync(cmd, { cwd: root, stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim(); } catch { return ''; } };
const read = (p) => (fs.existsSync(p) ? fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n') : '');
const write = (p, s) => { fs.mkdirSync(path.dirname(p), { recursive: true }); const old = read(p); if (old !== s) { fs.writeFileSync(p, s); return true; } return false; };

const state = fs.existsSync(stateFile) ? JSON.parse(fs.readFileSync(stateFile, 'utf8')) : { lastCommit: null, components: [], buttonKinds: [], memoryStamp: 0 };

// ---------- 1. catalog ----------
const idx = read(path.join(root, 'docs/design-system-components.md'));
const comps = [...idx.matchAll(/^\| \[([^\]]+)\]\(([^)]+)\) \| `([^`]+)` \| ([^|]*) \| ([^|]*) \|/gm)].map((m) => ({ name: m[1], doc: m[2].replace('../', ''), file: m[3], purpose: m[4].trim(), variants: m[5].trim() }));
const btn = read(path.join(root, 'src/design-system/primitives/Button.tsx'));
const union = (re) => { const m = btn.match(re); return m ? [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]) : []; };
const buttonKinds = union(/export type ButtonKind = ([^;]+);/);
const buttonSizes = union(/export type ButtonSize = ([^;]+);/);
const keys = (file, name) => { const m = read(path.join(root, file)).match(new RegExp('export const ' + name + ' = \\{([\\s\\S]*?)\\n\\}( as const)?;')); return m ? [...m[1].matchAll(/^\s{2}(\w+):/gm)].map((x) => x[1]) : []; };
const radiiLine = (read(path.join(root, 'src/design-system/tokens/radius.ts')).match(/export const radii = \{([^}]*)\}/) || [, ''])[1].replace(/\s+/g, ' ').trim();
const sizesLine = (read(path.join(root, 'src/design-system/tokens/typography.ts')).match(/export const fontSizes = \{([^}]*)\}/) || [, ''])[1].replace(/\s+/g, ' ').trim();
const claude = read(path.join(root, 'CLAUDE.md'));
const rules = (claude.match(/## Design system rules \(for every change\)([\s\S]*)$/) || [, ''])[1].trim();

let cat = `# Catalogue (generated, do not edit)

Generated by \`scripts/skill/learn.js\` from the code. Run \`npm run skill:learn\` to refresh it. The rules and judgement are in SKILL.md and learned.md.

## Library components (src/design-system)

| Component | Source | Purpose | Variants and states |
|---|---|---|---|
${comps.map((c) => `| [${c.name}](../../../${c.doc}) | \`${c.file}\` | ${c.purpose} | ${c.variants} |`).join('\n')}

## Button

- Kinds: ${buttonKinds.map((k) => '`' + k + '`').join(', ')}
- Sizes: ${buttonSizes.map((k) => '`' + k + '`').join(', ')}

## Tokens (src/design-system/tokens)

- Colour groups: \`fixed\` (${keys('src/design-system/tokens/colors.ts', 'fixed').join(', ')}), \`onDark\` (${keys('src/design-system/tokens/colors.ts', 'onDark').join(', ')}), \`gradients\` (${keys('src/design-system/tokens/colors.ts', 'gradients').join(', ')}); theme colours come from \`useTheme()\`.
- Radii: ${radiiLine}
- Font sizes: ${sizesLine}

## Rules every change must follow (from CLAUDE.md)

${rules}
`;
const catChanged = write(path.join(skill, 'catalog.md'), cat);

// ---------- 2. changelog ----------
const head = sh('git rev-parse HEAD');
const uiPaths = 'src/design-system src/components src/features src/app src/lib CLAUDE.md docs/design-system-components.md';
let entries = [];
if (head && state.lastCommit !== head) {
  const range = state.lastCommit && sh(`git cat-file -t ${state.lastCommit}`) === 'commit' ? `${state.lastCommit}..HEAD` : '-30';
  const raw = sh(`git log ${range} --no-merges --date=short --pretty=format:%h%x09%ad%x09%s -- ${uiPaths}`);
  entries = raw ? raw.split('\n').map((l) => l.split('\t')) : [];
}
let logChanged = false;
if (entries.length) {
  const prev = read(path.join(skill, 'CHANGELOG.md')) || '# Design changelog (generated)\n\nEvery commit that touched the UI, newest first. Written by `scripts/skill/learn.js`.\n';
  const [title, ...body] = prev.split('\n');
  const area = (h) => { const f = sh(`git show --name-only --pretty=format: ${h}`).split('\n').filter(Boolean); const a = new Set(); f.forEach((x) => { if (/design-system\/(primitives|patterns)/.test(x)) a.add('library'); else if (/design-system\/tokens/.test(x)) a.add('tokens'); else if (/^src\/app/.test(x)) a.add('screens'); else if (/^src\/features/.test(x)) a.add('features'); else if (/^docs|CLAUDE/.test(x)) a.add('docs'); }); return [...a].join(', ') || 'other'; };
  const block = entries.map(([h, d, s]) => `- ${d} \`${h}\` ${s} (${area(h)})`).join('\n');
  logChanged = write(path.join(skill, 'CHANGELOG.md'), `${title}\n\n${block}\n${body.join('\n').replace(/^\n+/, '\n')}`);
}

// ---------- 3. pending review ----------
const pend = [];
const names = comps.map((c) => c.name);
const addedC = names.filter((n) => !state.components.includes(n)), removedC = state.components.filter((n) => !names.includes(n));
const addedK = buttonKinds.filter((k) => !state.buttonKinds.includes(k));
if (state.components.length && addedC.length) pend.push(`- New library components: ${addedC.join(', ')}. Add the pattern to SKILL.md (when to use it, what it replaces).`);
if (state.components.length && removedC.length) pend.push(`- Library components removed or renamed: ${removedC.join(', ')}. Remove them from SKILL.md.`);
if (state.buttonKinds.length && addedK.length) pend.push(`- New Button kinds: ${addedK.join(', ')}. Say where each one is used.`);
const memDir = path.join(process.env.USERPROFILE || process.env.HOME || '', '.claude/projects/C--Users-rohitashav-garg-Desktop-Yourpal/memory');
let memStamp = state.memoryStamp || 0;
if (fs.existsSync(memDir)) {
  for (const f of fs.readdirSync(memDir).filter((x) => x.endsWith('.md') && x !== 'MEMORY.md')) {
    const m = fs.statSync(path.join(memDir, f)).mtimeMs;
    if (m > (state.memoryStamp || 0) && /type: feedback/.test(read(path.join(memDir, f)))) pend.push(`- Designer feedback saved or changed in memory: ${f}. Turn it into a rule in learned.md.`);
    memStamp = Math.max(memStamp, m);
  }
}
if (entries.length) pend.push(`- ${entries.length} UI commit(s) since the last review (see CHANGELOG.md). Read the diffs for new patterns: states, copy, layout, motion.`);
let pendChanged = false;
if (pend.length) {
  const prev = read(path.join(skill, 'pending-review.md'));
  const keep = prev.split('\n').filter((l) => l.startsWith('- ') && !pend.includes(l));
  pendChanged = write(path.join(skill, 'pending-review.md'), `# Pending review (generated)\n\nThings that changed since the skill was last reviewed. The yourpal-design-learner agent turns them into rules and empties this file.\n\n${[...new Set([...keep, ...pend])].join('\n')}\n`);
}

fs.writeFileSync(stateFile, JSON.stringify({ lastCommit: head || state.lastCommit, components: names, buttonKinds, memoryStamp: memStamp }, null, 1));
log(`skill: catalog ${catChanged ? 'updated' : 'unchanged'} (${comps.length} components, ${buttonKinds.length} Button kinds); changelog ${logChanged ? '+' + entries.length : 'unchanged'}; pending review ${pend.length ? pend.length + ' new' : 'nothing new'}`);
